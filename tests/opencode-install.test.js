'use strict';
// opencode/install.js and opencode/convert.js: what the plugin's agents, command and skills become
// for OpenCode 2.x, and an installer that never touches a file it didn't write.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { fileURLToPath } = require('url');
const { write } = require('./helpers');
const convert = require('../opencode/convert');
const installer = require('../opencode/install');

const ROOT = path.join(__dirname, '..');
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'dwc-oc-'));
const read = (dir, rel) => fs.readFileSync(path.join(dir, rel), 'utf8');
const fields = (text) => Object.fromEntries(convert.splitFrontmatter(text).fields);
const META = { version: '9.9.9', source: 'x.md', root: '/clone' };

test('an agent becomes a V2 subagent: deny rules for what it wasn\'t given, no Claude model', () => {
  const src = '---\nname: auditor\ndescription: "Reads, \\"never\\" writes."\ntools: Read, Grep, Glob, Bash\nmodel: sonnet\ncolor: cyan\n---\n\nYou audit.\n';
  const out = convert.agent(src, META);
  const f = fields(out);
  assert.equal(f.description, '"Reads, \\"never\\" writes."', 'the description is kept as written');
  assert.equal(f.mode, 'subagent');
  for (const gone of ['name', 'tools', 'model', 'color']) assert.equal(f[gone], undefined, gone + ' is dropped');
  assert.match(out, /permissions:\n {2}- action: edit\n {4}resource: "\*"\n {4}effect: deny/);
  assert.doesNotMatch(out, /action: shell/, 'Bash was granted');
  assert.match(out, /generated by opencode\/install\.js from x\.md/);
  assert.match(out, /\n\nYou audit\.\n$/);
});

test('an agent without a tools line keeps every permission it inherits', () => {
  const out = convert.agent('---\ndescription: d\n---\nBody\n', META);
  assert.doesNotMatch(out, /permissions:/);
});

test('a command loses its Claude-only fields and gets the clone\'s real path', () => {
  const src = '---\nname: setup\ndescription: "Sets up."\nargument-hint: "[n]"\nallowed-tools: Read, Write\n---\n\nRun node ${CLAUDE_PLUGIN_ROOT}/hooks/scripts/x.js with $ARGUMENTS.\n';
  const out = convert.command(src, Object.assign({}, META, { root: 'C:\\clone' }));
  assert.deepEqual(Object.keys(fields(out)), ['description']);
  assert.match(out, /Run node C:\/clone\/hooks\/scripts\/x\.js with \$ARGUMENTS\./);
  assert.doesNotMatch(out, /CLAUDE_PLUGIN_ROOT/);
  assert.match(out, /> \*\*In OpenCode\.\*\*/);
});

test('a skill keeps its body and only the frontmatter fields OpenCode knows', () => {
  const out = convert.skill('---\nname: spec\ndescription: "Writes specs."\nuser-invocable: true\n---\n\n# Spec\n', META);
  assert.deepEqual(fields(out), { name: 'spec', description: '"Writes specs."' });
  assert.match(out, /\n\n# Spec\n$/);
});

test('installing writes every file with its marker, and running it again changes nothing', () => {
  const dir = tmp();
  const results = installer.install(dir, installer.plan(ROOT), false);
  const rels = results.map((r) => r.rel);
  for (const rel of ['plugins/dev-workflow-core.js', 'agents/spec-updater.md', 'agents/docs-consistency-auditor.md',
    'commands/setup-project.md', 'skills/feature-spec/SKILL.md', 'skills/human-verification/SKILL.md']) {
    assert.ok(rels.includes(rel), rel + ' is installed');
    assert.ok(read(dir, rel).includes(convert.MARK), rel + ' carries the marker');
  }
  assert.ok(results.every((r) => r.status === 'written'));
  assert.ok(installer.install(dir, installer.plan(ROOT), false).every((r) => r.status === 'unchanged'));
});

test('the installed plugin file points at this clone\'s plugin', () => {
  const dir = tmp();
  installer.install(dir, installer.plan(ROOT), false);
  const m = /from "(file:[^"]+)"/.exec(read(dir, 'plugins/dev-workflow-core.js'));
  assert.ok(m, 'an import from a file URL');
  assert.equal(path.resolve(fileURLToPath(m[1])), path.resolve(ROOT, 'opencode', 'plugin', 'index.js'));
});

test('the installed files keep no Claude-only placeholder, and every agent is a subagent', () => {
  const dir = tmp();
  installer.install(dir, installer.plan(ROOT), false);
  assert.doesNotMatch(read(dir, 'commands/setup-project.md'), /CLAUDE_PLUGIN_ROOT/);
  for (const name of fs.readdirSync(path.join(dir, 'agents'))) {
    const f = fields(read(dir, 'agents/' + name));
    assert.equal(f.mode, 'subagent', name);
    assert.ok(f.description, name + ' has a description');
    assert.equal(f.model, undefined, name);
  }
});

test('a file the installer didn\'t write is neither overwritten nor removed', () => {
  const dir = tmp();
  write(dir, 'agents/spec-updater.md', 'mine\n');
  const results = installer.install(dir, installer.plan(ROOT), false);
  assert.equal(results.find((r) => r.rel === 'agents/spec-updater.md').status, 'refused');
  assert.equal(read(dir, 'agents/spec-updater.md'), 'mine\n');

  const removed = installer.uninstall(dir, installer.plan(ROOT), false);
  assert.equal(removed.find((r) => r.rel === 'agents/spec-updater.md').status, 'refused');
  assert.equal(read(dir, 'agents/spec-updater.md'), 'mine\n');
  assert.equal(removed.find((r) => r.rel === 'commands/setup-project.md').status, 'removed');
  assert.ok(!fs.existsSync(path.join(dir, 'skills', 'feature-spec')), 'an emptied skill folder goes too');
});

test('a dry run writes nothing; --project targets the project\'s .opencode folder', () => {
  const dir = tmp();
  assert.ok(installer.install(dir, installer.plan(ROOT), true).every((r) => r.status === 'written'));
  assert.deepEqual(fs.readdirSync(dir), []);
  assert.equal(installer.targetDir(installer.parseArgs(['--project', dir])), path.join(dir, '.opencode'));
  assert.throws(() => installer.parseArgs(['--dir']), /need a folder/);
  assert.throws(() => installer.parseArgs(['--global']), /Unknown argument/);
});
